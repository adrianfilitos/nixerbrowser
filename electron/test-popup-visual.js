const { app, BrowserWindow } = require('electron')
const path = require('path')
const os = require('os')
const fs = require('fs')
const http = require('http')
process.env.NIXER_USER_DATA = path.join(os.tmpdir(), 'nixer-popup-visual-test')
fs.rmSync(process.env.NIXER_USER_DATA, { recursive: true, force: true })
require('./main')
const delay = (ms) => new Promise((r) => setTimeout(r, ms))
app.whenReady().then(async () => {
  let win = null
  for (let i = 0; i < 25 && !win; i++) { const ws = BrowserWindow.getAllWindows(); if (ws.length) win = ws[0]; else await delay(400) }
  const ui = win.webContents
  const waitTab = () => ui.executeJavaScript(`(async () => { for (let i = 0; i < 60; i++) { const t = document.querySelector('.tab'); if (t && t.dataset.id) return t.dataset.id; await new Promise(r => setTimeout(r, 200)) } return null })()`)
  const tabId = await waitTab()
  if (!tabId) { console.log('NO_TAB'); app.exit(2); return }
  await delay(1000)
  const server = http.createServer((req, res) => { res.setHeader('Content-Type', 'text/html'); res.end('<html><body style="background:#ffffff"><h1>PAGE-VISIBLE</h1></body></html>') })
  await new Promise((r) => server.listen(0, '127.0.0.1', r))
  const port = server.address().port
  await ui.executeJavaScript(`window.api.tabLoad('${tabId}', 'http://127.0.0.1:${port}/')`)
  await delay(2500)
  win.show(); win.focus()
  await delay(1000)
  console.log('READY_HWND=' + win.getNativeWindowHandle().readInt32LE(0))
  const btnRect = await ui.executeJavaScript(`(() => { const b = document.querySelector('.menu-btn'); if (!b) return null; const r = b.getBoundingClientRect(); return { left: Math.round(r.left), right: Math.round(r.right), bottom: Math.round(r.bottom), innerWidth: window.innerWidth } })()`)
  console.log('BTN_RECT:', JSON.stringify(btnRect))
  await ui.executeJavaScript(`document.querySelector('.menu-btn').click(); true`)
  await delay(1500)
  console.log('POPUP_BOUNDS:', JSON.stringify(require('./popups').debugBounds()))
  console.log('POPUP_OPEN')
  await new Promise((r) => setTimeout(r, 60000))
  server.close()
  app.exit(0)
}).catch((e) => { console.log('ERR', e && e.stack); app.exit(2) })
setTimeout(() => { console.log('HARD_TIMEOUT'); app.exit(3) }, 120000)
