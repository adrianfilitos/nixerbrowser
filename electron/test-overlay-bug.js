const { app, BrowserWindow } = require('electron')
const path = require('path')
const os = require('os')
const fs = require('fs')
const http = require('http')
process.env.NIXER_USER_DATA = path.join(os.tmpdir(), 'nixer-overlay-bug-test')
fs.rmSync(process.env.NIXER_USER_DATA, { recursive: true, force: true })
require('./main')
const delay = (ms) => new Promise((r) => setTimeout(r, ms))
app.whenReady().then(async () => {
  let win = null
  for (let i = 0; i < 25 && !win; i++) { const ws = BrowserWindow.getAllWindows(); if (ws.length) win = ws[0]; else await delay(400) }
  const ui = win.webContents
  ui.on('console-message', (_e, _l, msg) => console.log('[UI]', msg))
  const waitTab = () => ui.executeJavaScript(`(async () => { for (let i = 0; i < 60; i++) { const t = document.querySelector('.tab'); if (t && t.dataset.id) return t.dataset.id; await new Promise(r => setTimeout(r, 200)) } return null })()`)
  const tabId = await waitTab()
  if (!tabId) { console.log('NO_TAB'); app.exit(2); return }
  await delay(1000)
  const server = http.createServer((req, res) => { res.setHeader('Content-Type', 'text/html'); res.end('<html><body><h1>REALPAGE</h1></body></html>') })
  await new Promise((r) => server.listen(0, '127.0.0.1', r))
  const port = server.address().port
  await ui.executeJavaScript(`window.api.tabLoad('${tabId}', 'http://127.0.0.1:${port}/')`)
  await delay(2500)
  const urlBefore = await ui.executeJavaScript(`window.api.tabGetUrl('${tabId}')`)
  const titleBefore = await ui.executeJavaScript(`document.querySelector('.tab.active .tab-title').textContent`)
  console.log('BEFORE:', JSON.stringify({ urlBefore, titleBefore }))
  await ui.executeJavaScript(`document.querySelector('.menu-btn').click(); true`)
  await delay(600)
  const ddVisible = await ui.executeJavaScript(`!!document.querySelector('.dropdown')`)
  const urlDuring = await ui.executeJavaScript(`window.api.tabGetUrl('${tabId}')`)
  console.log('DURING:', JSON.stringify({ ddVisible, urlDuring }))
  await ui.executeJavaScript(`document.querySelector('.menu-btn').click(); true`)
  await delay(700)
  const urlAfter = await ui.executeJavaScript(`window.api.tabGetUrl('${tabId}')`)
  const titleAfter = await ui.executeJavaScript(`document.querySelector('.tab.active .tab-title') ? document.querySelector('.tab.active .tab-title').textContent : 'NO_ACTIVE'`)
  const tabsAfter = await ui.executeJavaScript(`Array.from(document.querySelectorAll('.tab')).map(t => ({ id: t.dataset.id, title: t.querySelector('.tab-title').textContent }))`)
  console.log('AFTER:', JSON.stringify({ urlAfter, titleAfter, tabsAfter }))
  server.close()
  win.close()
  setTimeout(() => app.exit(0), 300)
}).catch((e) => { console.log('ERR', e && e.stack); app.exit(2) })
setTimeout(() => { console.log('HARD_TIMEOUT'); app.exit(3) }, 90000)
